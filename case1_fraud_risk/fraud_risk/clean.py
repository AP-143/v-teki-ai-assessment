"""Load the raw CSV tables, fix known data-quality problems, and report what was fixed."""
import argparse
import re
from pathlib import Path

import pandas as pd

from fraud_risk import CASE_DIR
from fraud_risk.features import LABEL
from fraud_risk.privacy import REQUIRED_COLUMNS, setup_logging


TIME_COLUMNS = ["signup_date", "blocked_at", "timestamp"]


def load_tables(data_dir):
    """Read the three CSVs; raise ValueError if a required column is missing."""
    tables = {}
    for name, required in REQUIRED_COLUMNS.items():
        df = pd.read_csv(Path(data_dir) / f"{name}.csv", dtype={"customer_id": str, "device_id": str})
        missing = sorted(set(required) - set(df.columns))
        if missing:
            raise ValueError(f"{name}.csv is missing required columns: {missing}")
        for col in TIME_COLUMNS:
            if col in df:
                df[col] = pd.to_datetime(df[col], errors="coerce")
        tables[name] = df
    return tables


def normalize_customer_id(value):
    """'c-12', ' 12 ', 'CUST_12', 'C00012 ' -> 'C00012'; None when there is no number."""
    digits = re.sub(r"\D", "", value) if isinstance(value, str) else ""
    return f"C{int(digits):05d}" if digits else None


def clean_tables(tables):
    """Return cleaned copies of the tables plus a {check: row count} data-quality report."""
    customers, tx, logins = (tables[n].copy() for n in ("customers", "transactions", "login_events"))
    report = {"transactions: rows received": len(tx)}

    for name, df in (("transactions", tx), ("login_events", logins)):
        normalized = df["customer_id"].map(normalize_customer_id)
        report[f"{name}: inconsistent customer_id (normalized)"] = int((normalized != df["customer_id"]).sum())
        df["customer_id"] = normalized

    before = len(tx)
    tx = tx.drop_duplicates("transaction_id")
    report["transactions: duplicate events (removed)"] = before - len(tx)

    missing_time = tx["timestamp"].isna()
    report["transactions: missing timestamp (dropped, cannot be placed in time)"] = int(missing_time.sum())
    tx = tx[~missing_time]

    report["transactions: missing device_id (set to UNKNOWN)"] = int(tx["device_id"].isna().sum())
    tx["device_id"] = tx["device_id"].fillna("UNKNOWN")

    known = customers["customer_id"]
    report["transactions: unknown customer (dropped)"] = int((~tx["customer_id"].isin(known)).sum())
    report["login_events: unknown customer (dropped)"] = int((~logins["customer_id"].isin(known)).sum())
    tx = tx[tx["customer_id"].isin(known)]
    logins = logins[logins["customer_id"].isin(known)]
    report["transactions: rows kept"] = len(tx)

    if LABEL in tx and "is_blocked" in customers:
        victims = tx.loc[tx[LABEL] == 1, "customer_id"].unique()
        blocked = customers["is_blocked"].astype(bool)
        report["customers: blocked"] = int(blocked.sum())
        report["customers: blocked WITHOUT confirmed fraud (why is_blocked is not a label)"] = int(
            (blocked & ~customers["customer_id"].isin(victims)).sum())
        report["customers: confirmed fraud but NOT blocked"] = int(
            (~blocked & customers["customer_id"].isin(victims)).sum())

    return {"customers": customers, "transactions": tx, "login_events": logins}, report


def write_quality_report(report, path):
    lines = ["# Data quality report", "",
             "Generated by `python -m fraud_risk.clean` from `data/raw/`. Counts are rows unless stated.", "",
             "| Check | Count |", "|---|---:|"]
    lines += [f"| {check} | {count} |" for check, count in report.items()]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description="Clean the raw tables and write the data-quality report.")
    parser.add_argument("--data-dir", type=Path, default=CASE_DIR / "data" / "raw")
    parser.add_argument("--out", type=Path, default=CASE_DIR / "reports" / "data_quality.md")
    args = parser.parse_args(argv)
    log = setup_logging()

    try:
        _, report = clean_tables(load_tables(args.data_dir))
    except (OSError, ValueError) as err:
        log.error("%s", err)
        raise SystemExit(2)
    write_quality_report(report, args.out)
    log.info("Wrote data-quality report to %s", args.out)


if __name__ == "__main__":
    main()
